// Parameters for the 'arcade' hit sound set: each sound is a few decaying partials plus
// noise in 1/3-octave bands with fitted envelopes (attack, fast decay until `kn` seconds
// after the peak, then slow decay). Fitted to measurements of the cabinet's sounds; this file
// holds only these numbers, no audio.

export interface ModelPartial {
  /** Hz */
  f: number
  /** amplitude */
  a: number
  /** attack (s) */
  at: number
  /** decay rates (1/s) before and after the knee */
  k1: number
  k2: number
  /** knee, seconds after the peak */
  kn: number
}

export interface ModelBand {
  /** band centre, Hz */
  fc: number
  /** gain applied to unit noise through the band filter */
  g: number
  at: number
  k1: number
  k2: number
  kn: number
}

export interface SoundModel {
  seconds: number
  partials: ModelPartial[]
  bands: ModelBand[]
}

